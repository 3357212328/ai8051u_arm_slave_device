#include "delay.h"
#include "intrins.h"

// ====================================================================
// 阻塞延时 (基于 NOP 指令, 适配 40MHz 内部高速IRC)
// --------------------------------------------------------------------
// 40MHz 下 1 个机器周期 = 25ns。循环体 36 NOP + 循环开销(~6周期)
// ≈ 42 周期 ≈ 1.05us, 略高于 1us 以保证 DHT11 起始脉冲(20ms)足够长。
// 若修改主频请同步调整下面的 NOP 数量。
// ====================================================================

void delay_us(uint16_t nus)
{
    do
    {
        _nop_();_nop_();_nop_();_nop_();_nop_();_nop_();_nop_();_nop_();
        _nop_();_nop_();_nop_();_nop_();_nop_();_nop_();_nop_();_nop_();
        _nop_();_nop_();_nop_();_nop_();_nop_();_nop_();_nop_();_nop_();
        _nop_();_nop_();_nop_();_nop_();_nop_();_nop_();_nop_();_nop_();
        _nop_();_nop_();_nop_();_nop_();
    } while (--nus);
}

void delay_ms(uint16_t nms)
{
    while (nms--)
    {
        delay_us(1000);
    }
}
